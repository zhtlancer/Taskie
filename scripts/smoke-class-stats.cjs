// Build first. Real API, isolated data, phone/tablet light/dark tuition and attendance flows.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright');
const { getDb } = require('../backend/src/db');
const { getTodayDate, shiftDate } = require('../backend/src/utils/date');
const buildApp = require('../backend/src/app');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'taskie-class-stats-'));
const db = getDb(':memory:');
db.prepare("UPDATE settings SET value = '0' WHERE key = 'parent_pin_is_default'").run();
const app = buildApp({ db, logger: false, deviceAuth: false, backupIntervalHours: 0,
  uploadDir: path.join(dir, 'uploads'), backupDir: path.join(dir, 'backups'), authorizedTokensFile: path.join(dir, 'tokens'), clientDistDir: path.resolve(__dirname, '../frontend/dist') });
let browser;
async function main() {
  await app.ready();
  const first = app.services.childrenService.createChild({ name: '出勤甲' });
  const second = app.services.childrenService.createChild({ name: '出勤乙' });
  const today = getTodayDate(), yesterday = shiftDate(today, -1), past = shiftDate(today, -2);
  app.services.classStatsService.now = () => ({ today, clock: '00:00' });
  const token = app.jwt.sign({ role: 'parent', epoch: app.sessionEpoch() });
  const base = await app.listen({ host: '127.0.0.1', port: 0 });
  browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox'] });
  const errors = [];
  for (const width of [390, 1180]) for (const colorScheme of ['light', 'dark']) {
    const title = `统计钢琴-${width}-${colorScheme}`;
    const cls = app.services.scheduleService.createClass({ title, start_date: past, days_of_week: [0, 1, 2, 3, 4, 5, 6], start_time: '16:00', end_time: '17:00', total_lessons: 5, create_task: true });
    const context = await browser.newContext({ viewport: { width, height: width === 390 ? 844 : 820 }, colorScheme, timezoneId: 'America/Los_Angeles' });
    await context.addInitScript(value => sessionStorage.setItem('taskie_parent_token', value), token);
    const page = await context.newPage(); page.setDefaultTimeout(10000);
    page.on('pageerror', error => errors.push(error.message));
    await page.route('**/*', route => new URL(route.request().url()).origin === base ? route.continue() : route.abort());
    await page.goto(`${base}/parent/schedule?child=${first.id}`, { waitUntil: 'networkidle' });
    const card = page.locator('div.p-4.rounded-2xl').filter({ has: page.getByText(title, { exact: true }) });
    await card.getByText('待确认 2 次', { exact: true }).waitFor();
    await card.getByRole('button', { name: '出勤与学费', exact: true }).click();
    let modal = page.getByRole('dialog', { name: `${first.name} · ${title}`, exact: true });
    await modal.getByText('未确认 · 未消课', { exact: true }).first().waitFor();
    let row = modal.locator(`[data-lesson-date="${past}"]`);
    await row.getByRole('button', { name: '记录出勤', exact: true }).click();
    await row.getByLabel('出勤备注').fill('家长核实到课');
    const attendanceUrl = `**/outside-classes/${cls.id}/attendance`;
    await page.route(attendanceUrl, route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: '保存失败，请重试' }) }));
    await row.getByRole('button', { name: '保存出勤', exact: true }).click();
    await modal.getByRole('alert').getByText('保存失败，请重试', { exact: true }).waitFor();
    assert.equal(await row.getByLabel('出勤备注').inputValue(), '家长核实到课');
    await page.unroute(attendanceUrl);
    let release, seen;
    const gate = new Promise(resolve => { release = resolve; });
    const arrived = new Promise(resolve => { seen = resolve; });
    await page.route(attendanceUrl, async route => { seen(); await gate; await route.continue(); });
    await row.getByRole('button', { name: '保存出勤', exact: true }).click(); await arrived;
    assert.equal(await modal.getByRole('button', { name: '关闭', exact: true }).isDisabled(), true);
    await page.keyboard.press('Escape'); assert.equal(await modal.count(), 1);
    release();
    await row.getByText('已上课 · 消课 1 次', { exact: true }).waitFor();
    await page.unroute(attendanceUrl);
    await modal.getByLabel('本期总学费（元，选填）').fill('100.01');
    await modal.getByRole('button', { name: '保存学费', exact: true }).click();
    await modal.getByText('平均每次 ¥20.00 · 已消耗 ¥20.00 · 剩余 ¥80.01', { exact: true }).waitFor();
    row = modal.locator(`[data-lesson-date="${yesterday}"]`);
    await row.getByRole('button', { name: '记录出勤', exact: true }).click();
    await row.getByLabel('出勤状态').selectOption('absent');
    await row.getByLabel('本次消课（扣 1 次）').check();
    await row.getByRole('button', { name: '保存出勤', exact: true }).click();
    await row.getByText('缺席 · 消课 1 次', { exact: true }).waitFor();
    await modal.getByText('平均每次 ¥20.00 · 已消耗 ¥40.00 · 剩余 ¥60.01', { exact: true }).waitFor();
    await modal.getByRole('button', { name: '关闭', exact: true }).click();
    await page.getByRole('button', { name: new RegExp(second.name) }).click();
    await card.getByRole('button', { name: '出勤与学费', exact: true }).click();
    modal = page.getByRole('dialog', { name: `${second.name} · ${title}`, exact: true });
    await modal.getByLabel('本期总学费（元，选填）').waitFor();
    assert.equal(await modal.getByLabel('本期总学费（元，选填）').inputValue(), '');
    await modal.getByLabel('本期总学费（元，选填）').fill('200');
    await modal.getByRole('button', { name: '保存学费', exact: true }).click();
    await modal.getByText('总学费 ¥200.00', { exact: true }).waitFor();
    assert.equal(app.services.classStatsService.summary(app.services.classStatsService.context(cls.id, first.id)).total_fee_cents, 10001);
    assert.equal(app.services.classStatsService.summary(app.services.classStatsService.context(cls.id, second.id)).attended, 0);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await modal.getByRole('button', { name: '关闭', exact: true }).click();
    await page.goto(`${base}/parent/dashboard`, { waitUntil: 'networkidle' });
    const home = page.locator('div.rounded-3xl').filter({ has: page.getByRole('heading', { name: first.name, exact: true }) });
    await home.locator('[data-class-overview]').waitFor();
    await home.locator('[data-class-overview]').click();
    await page.waitForURL(url => url.pathname === '/parent/schedule' && url.searchParams.get('child') === first.id);
    await card.getByText('已上', { exact: false }).first().waitFor();
    await card.getByRole('button', { name: '删除', exact: true }).click();
    let confirmation = page.getByRole('dialog', { name: '确认操作', exact: true });
    await confirmation.getByText(/出勤、学费和未完成打卡任务会一起删除/).waitFor();
    await confirmation.getByRole('button', { name: '取消', exact: true }).click();
    assert.equal(db.prepare('SELECT COUNT(*) AS n FROM outside_class_attendance WHERE class_id = ?').get(cls.id).n, 2);
    await card.getByRole('button', { name: '删除', exact: true }).click();
    confirmation = page.getByRole('dialog', { name: '确认操作', exact: true });
    const deleted = page.waitForResponse(r => r.request().method() === 'DELETE' && r.url().endsWith(`/outside-classes/${cls.id}`));
    await confirmation.getByRole('button', { name: '确认', exact: true }).click();
    assert.equal((await deleted).status(), 200);
    assert.equal(db.prepare('SELECT COUNT(*) AS n FROM outside_class_attendance WHERE class_id = ?').get(cls.id).n, 0);
    assert.equal(db.prepare('SELECT COUNT(*) AS n FROM outside_class_fees WHERE class_id = ?').get(cls.id).n, 0);
    assert.deepEqual(errors, []);
    await context.close();
    console.log(`PASS ${width}px ${colorScheme}: attendance, failure/retry, busy close guard, fees, child isolation, dashboard link and explicit deletion`);
  }
}
main().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => {
  if (browser) await browser.close(); await app.close(); db.close(); fs.rmSync(dir, { recursive: true, force: true });
});
